#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
RPC_URL="${LOCAL_RPC_URL:-http://127.0.0.1:8545}"
SENDER="${SENDER:-0xf39Fd6e51aad88F6F4ce6aB8827279cffFb92266}"
FORGE="bash $ROOT/scripts/forge.sh"

if ! $FORGE --version >/dev/null 2>&1; then
  echo "Foundry not found. Install it from https://getfoundry.sh and rerun." >&2
  exit 1
fi

if ! curl -s -X POST "$RPC_URL" -H 'content-type: application/json' \
  --data '{"jsonrpc":"2.0","id":1,"method":"eth_chainId","params":[]}' | grep -q result; then
  echo "No JSON-RPC node at $RPC_URL. Start one with: npm run chain:node" >&2
  exit 1
fi

echo "Deploying PactRail contracts to $RPC_URL…"
(
  cd contracts
  $FORGE script script/Deploy.s.sol:Deploy \
    --rpc-url "$RPC_URL" \
    --broadcast \
    --unlocked \
    --sender "$SENDER" \
    >/tmp/pactrail-deploy.log 2>&1
)
cat /tmp/pactrail-deploy.log

BROADCAST="contracts/broadcast/Deploy.s.sol/31337/run-latest.json"
if [[ ! -f "$BROADCAST" ]]; then
  echo "Broadcast file not found at $BROADCAST" >&2
  exit 1
fi

read -r TOKEN ESCROW < <(python3 - "$BROADCAST" <<'PY'
import json, sys
data = json.load(open(sys.argv[1]))
token = None
escrow = None
for tx in data.get("transactions", []):
    name = tx.get("contractName")
    address = tx.get("contractAddress")
    if name == "MockStablecoin":
        token = address
    elif name == "AgreementEscrow":
        escrow = address
print(token, escrow)
PY
)

if [[ -z "$TOKEN" || -z "$ESCROW" || "$TOKEN" == "None" || "$ESCROW" == "None" ]]; then
  echo "Could not determine deployed addresses from $BROADCAST" >&2
  exit 1
fi

cat > .env.local <<ENV
# Generated by scripts/deploy-local.sh for local Anvil development.
NEXT_PUBLIC_DEFAULT_CHAIN=local
NEXT_PUBLIC_LOCAL_RPC_URL=$RPC_URL
NEXT_PUBLIC_LOCAL_ESCROW=$ESCROW
NEXT_PUBLIC_LOCAL_TOKEN=$TOKEN
NEXT_PUBLIC_LOCAL_TOKEN_SYMBOL=pUSDC
NEXT_PUBLIC_LOCAL_TOKEN_DECIMALS=6
ENV

echo
echo "Wrote .env.local"
echo "  AgreementEscrow: $ESCROW"
echo "  MockStablecoin:  $TOKEN"
echo "Restart the dev server to pick up the new environment."
